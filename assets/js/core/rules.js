function getRulesForMode(modeKey) {
    if (modeKey === 'basic') return RULES_BASIC;
    if (modeKey === 'lb+') return RULES_LB_PLUS;
    if (modeKey === 'lb-') return RULES_LB_MINUS;
    if (modeKey === 'bb+') return RULES_BB_PLUS;
    if (modeKey === 'bb-') return RULES_BB_MINUS;
    return RULES_BASIC;
}

function isAllowed(X, op, n, RULES) {
    const list = RULES[op + n];
    return list ? list.includes(X) : false;
}

function isSignatureStep(X, op, n, modeKey) {
    if (n === 0) return false;
    if (modeKey === 'lb+') {
        if (op !== '+' || n < 1 || n > 4) return false;
        return isAllowed(X, '+', n, RULES_LB_PLUS) && !isAllowed(X, '+', n, RULES_BASIC);
    }
    if (modeKey === 'lb-') {
        if (op !== '-' || n < 1 || n > 4) return false;
        return isAllowed(X, '-', n, RULES_LB_MINUS) && !isAllowed(X, '-', n, RULES_LB_PLUS);
    }
    if (modeKey === 'bb+') {
        if (op !== '+' || n < 1 || n > 9) return false;
        return isAllowed(X, '+', n, RULES_BB_PLUS) && !isAllowed(X, '+', n, RULES_LB_PLUS);
    }
    if (modeKey === 'bb-') {
        if (op !== '-' || n < 1 || n > 9) return false;
        return isAllowed(X, '-', n, RULES_BB_MINUS) && !isAllowed(X, '-', n, RULES_LB_MINUS);
    }
    return false;
}

function uiModeToKey(mode) {
    if (mode === 'fm-basic' || mode === 'sb-add-basic') return 'basic';
    if (mode === 'fm-lb-plus' || mode === 'sb-add-lb-plus') return 'lb+';
    if (mode === 'fm-lb-minus' || mode === 'sb-add-lb-minus') return 'lb-';
    if (mode === 'fm-bb-plus' || mode === 'sb-add-bb-plus') return 'bb+';
    if (mode === 'fm-bb-minus' || mode === 'sb-add-bb-minus') return 'bb-';
    return 'basic';
}